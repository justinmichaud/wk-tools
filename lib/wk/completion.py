"""`wk completion bash|zsh` from the command tables; workspace names and `values` lists are asked at TAB, of this machine only."""

import dataclasses
import os
import sys

from wk import decl, images, presets
from wk.places import Registry

SHELLS = ("bash", "zsh")
FUNCTION = os.path.join(os.path.dirname(os.path.abspath(__file__)), "completion.bash")


def local_workspaces(root, env=None):
    return Registry(root, env).local_workspaces()


def flags(t):
    return sorted(o.flag for o in t.opts)


def values_cmd(t):
    if t.values in t.subs:
        t = decl.under(t, t.subs[t.values])
    else:
        t = next((dataclasses.replace(t, **o.sets) for o in t.opts if o.flag == t.values), t)
    return t.values if t.where in ("local", "host") else ""


def _words(words):
    return "'%s'" % " ".join(words)


def _arm(name, t):
    subs = {v: decl.under(t, f) for v, f in t.subs.items()}
    valued = {o.flag for _, v, opts in decl.variants(name, t) for o in opts if o.value and not o.optional}
    slot = 1 if t.named() else 0
    return ("        %s) _wk_slot=%d; _wk_first_arg=%d; _wk_flags=%s; _wk_valued=%s; _wk_subverbs=%s; _wk_vslots=%s;"
            " _wk_vflags=%s; _wk_default=%s; _wk_vals=%s; _wk_preset=%s ;;\n"
            % (name, slot, slot, _words(flags(t)), _words(sorted(valued)), _words(subs),
               _words("%s:%d" % (v, 2 if s.named() else 0) for v, s in subs.items()),
               _words("%s:%s" % (v, ",".join(flags(s))) for v, s in subs.items()), _words([t.default]),
               _words([values_cmd(t)]), _words([t.preset])))


def generate(root, shell_name):
    tables = [(name, m.COMMAND) for name, m in decl.commands(root)]
    out = ["# wk %s completion -- generated by `wk completion %s`; eval this in your rc.\n" % (shell_name, shell_name)]
    if shell_name == "zsh":
        # bashcompinit's `complete` calls compdef, which needs compinit (a stock ~/.zshrc omits it); -C reads the dumpfile as it stands.
        out.append("autoload -U +X compinit && compinit -C\nautoload -U +X bashcompinit && bashcompinit\n")
    out.append("_wk_root=%s\n_wk_commands=%s\n_wk_presets=%s\n_wk_decl() {\n    case \"$1\" in\n"
               % (_words([str(root)]), _words(sorted([n for n, _ in tables] + ["completion"])), _words(presets.names())))
    out += [_arm(name, t) for name, t in tables]
    out.append("        completion) _wk_slot=0; _wk_first_arg=0; _wk_flags=''; _wk_valued=''; _wk_subverbs=%s; _wk_vslots='';"
               " _wk_vflags=''; _wk_default=''; _wk_vals=''; _wk_preset='' ;;\n        *) return 1 ;;\n    esac\n}\n\n"
               % _words(SHELLS))
    with open(FUNCTION) as fh:
        out.append(fh.read())
    return "".join(out)


def main(argv, env=None):
    if argv == ["--list-workspaces"]:
        for name in local_workspaces(images.root(), env):
            print(name)
        return 0
    sys.stderr.write("usage: python3 -m wk.completion --list-workspaces\n")
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
