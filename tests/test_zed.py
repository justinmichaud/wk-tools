TRANSPORT = os.path.join(str(REPO), "container", "ssh-transport")
INSTALL = ("podman", "exec", "wk-ws", "/opt/wk-tools/container/proxy/ensure-bridge.sh", "/bin/sh", "-c",
           "apt-get update -qq; apt-get install -y -qq --no-install-recommends openssh-server")
AUTHORISE = ("podman", "exec", "-i", "--user", "dev", "wk-ws", "/bin/sh", "-c")
ALIAS = ("\nHost wk-%s\n    # generated by wk -- removed by wk rm\n    HostName %s\n    User dev\n    StrictHostKeyChecking no\n"
         "    UserKnownHostsFile /dev/null\n    IdentityFile /state/wk/ssh/zed_ed25519\n    IdentitiesOnly yes\n    ProxyCommand %s\n")


def host_path(w, zed=False, bundle=False):
    """This host's PATH: a `zed` on it or not, and a `test` that answers for /Applications/Zed.app as `bundle` says."""
    (w.tmp / "hostbin").mkdir(exist_ok=True)
    tools = {"test": '[ "$2" = /Applications/Zed.app/Contents/MacOS/cli ] && exit %d; exit 1' % (not bundle), "zed": "exit 0"}
    for name in ("test", "zed") if zed else ("test",):
        (w.tmp / "hostbin" / name).write_text("#!/bin/sh\n%s\n" % tools[name])
        (w.tmp / "hostbin" / name).chmod(0o755)
    w.env["PATH"] = str(w.tmp / "hostbin")


def keygen(argv, f):
    f.files[argv[-1]], f.files[argv[-1] + ".pub"] = "PRIVATE\n", "ssh-ed25519 AAAAzed wk zed key\n"
    return Result(0)


def alias(w):
    return w.rel(w.files.get(os.path.join(w.env["HOME"], ".ssh", "config.d", "wk"), ""))


class ZedWorld(World):
    """Container workspaces whose podman WorkingDir is `home`; those in `sshd` have openssh-server, which the bridge's
    apt-get installs; ssh-keygen writes the key it is asked for. This host has no Zed until `host_path` gives it one."""

    def __init__(self, tmp, **kw):
        super().__init__(tmp, **kw)
        self.sshd, self.home = set(), "/home/dev"
        self.react(["podman", "inspect"], lambda a, f: Result(0, (f.home if "WorkingDir" in a[-1] else "running") + "\n")
                   if a[2] in f.containers else Result(125, "", "Error: no such object: %s" % a[2]))
        self.react(["podman", "exec"], self._exec_in)
        self.react(["podman", "exec", "-i"], lambda a, f: Result(0, "added\n"))
        self.answer(["chmod"])
        self.react(["ssh-keygen"], keygen)
        host_path(self)

    def _exec_in(self, argv, f):
        if "apt-get" in argv[-1]:
            f.sshd.add(argv[2])
        return Result(0 if argv[3:] != ["test", "-x", "/usr/sbin/sshd"] or argv[2] in f.sshd else 1)


class TestZedOnAContainer(WorkspaceTest):
    """`wk zed ws ...` typed on the machine holding container workspace `ws`."""
    world_class = ZedWorld

    def setUp(self):
        super().setUp()
        self.w.make("ws")
        self.w.effects = []

    def acts(self):
        return [self.w.rel(e[1])[:8] for e in self.w.effects if e[0] == "act"]

    def test_url_prints_the_alias_route_and_writes_its_proxycommand_block(self):
        """`unit zed.alias_is_proxycommand`"""
        self.assertEqual(self.wk(self.w, "zed", "ws", "--url")[:2], (0, "ssh://wk-ws/src/WebKit\n"))
        self.assertEqual(alias(self.w), ALIAS % ("ws", "wk-ws.container.invalid", TRANSPORT + " container ws"))

    def test_route_prints_the_user_src_and_proxy_and_needs_no_zed(self):
        self.assertEqual(self.wk(self.w, "zed", "ws", "--route")[:2], (0, "user=dev\nsrc=/src/WebKit\nproxy=%s container ws\n" % TRANSPORT))

    def test_sshd_and_this_machines_key_are_made_once_and_the_key_authorised_each_time(self):
        self.wk(self.w, "zed", "ws", "--url")
        self.assertEqual(self.acts(), [INSTALL, ("chmod", "0700", "/state/wk/ssh"), ("ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-C",
                                       "wk zed key (here)"), AUTHORISE, ("chmod", "0700", "/home/.ssh/config.d")])
        self.w.effects = []
        self.wk(self.w, "zed", "ws", "--url")
        self.assertEqual(self.acts(), [AUTHORISE])

    def test_a_dry_run_on_a_machine_without_its_key_prints_every_step_and_changes_nothing(self):
        host_path(self.w, zed=True)
        self.w.sshd.add("wk-ws")
        before = (dict(self.w.files), set(self.w.dirs))
        rc, _, err = self.wk(self.w, "zed", "ws", "--dry-run")
        self.assertEqual(re.findall(r"^would run: (\S+ \S+)", err, re.M), ["chmod 0700", "ssh-keygen -q", "podman exec", "chmod 0700",
                                                                            "zed ssh://wk-ws/src/WebKit"])
        self.assertEqual((rc, before), (0, (self.w.files, self.w.dirs)))

    def test_with_no_zed_on_path_the_bundle_cli_opens_it_and_with_neither_nothing_runs(self):
        self.w.sshd.add("wk-ws")
        host_path(self.w, bundle=True)
        rc, _, err = self.wk(self.w, "zed", "ws", "--dry-run")
        self.assertEqual((rc, err.splitlines()[-1]), (0, "would run: /Applications/Zed.app/Contents/MacOS/cli ssh://wk-ws/src/WebKit"))
        host_path(self.w)
        self.w.effects = []
        rc, _, err = self.wk(self.w, "zed", "ws")
        self.assertEqual((rc, err.splitlines()[0], self.w.mutations()),
                         (1, "error: zed is not installed (no 'zed' on PATH, no /Applications/Zed.app)", []))

    def test_a_container_podman_gives_no_home_for_is_refused(self):
        self.w.home = "/"
        rc, _, err = self.wk(self.w, "zed", "ws", "--url")
        self.assertEqual((rc, err.splitlines()[0], self.acts()), (1, "error: no container workspace called 'ws' on this machine.", []))

    def test_a_broken_workspace_is_refused_naming_its_repair(self):
        self.w.containers.discard("wk-ws")
        rc, _, err = self.wk(self.w, "zed", "ws", "--url")
        self.assertEqual((rc, err.splitlines()[1], self.acts()), (1, "    Repair:  wk rm ws    (then 'wk new ws')", []))


class PeerWorld(fakes.World):
    """This host and a peer workstation, `peer.example`, whose own wk lists `demo` and answers its route."""

    def __init__(self, tmp):
        super().__init__(tmp)
        (self.tmp / "machines").mkdir()
        (self.tmp / "machines" / "peer.conf").write_text("kind=peer\nhost=peer.example\n")
        self.env["WK_MACHINES_DIR"] = str(self.tmp / "machines")
        self.answer(["podman", "machine", "ssh"], rc=1)
        self.answer(["podman", "-c", "wk", "inspect"], rc=125, err="Error: no such object")
        self.answer(["chmod"])
        self.react(["ssh-keygen"], keygen)
        self.react(["ssh"], lambda a, f: Result(0, LINUX_PROBE) if "uname -s" in a[-1] else
                   Result(0, json.dumps({"workspaces": [{"name": "demo", "state": "running"}]})) if "wk ls --json" in a[-1] else
                   Result(0, "user=dev\nsrc=/src/WebKit\nproxy=/opt/wk-tools/container/ssh-transport demo\n") if "wk zed demo --route" in a[-1]
                   else Result(127, "", "no answer from peer.example"))
        self.reg = FakeRegistry(self.env, self)


class TestZedOnAPeer(FlowTest):
    def test_a_peer_workspace_is_reached_through_a_two_hop_proxycommand_its_route_asked_with_this_machines_key(self):
        w = PeerWorld(self.tmp)
        self.assertEqual(self.wk(w, "zed", "demo", "--url")[:2], (0, "ssh://wk-demo/src/WebKit\n"))
        self.assertEqual(alias(w), ALIAS % ("demo", "wk-demo.peer.invalid", "ssh peer.example /opt/wk-tools/container/ssh-transport demo"))
        asked = [shlex.split(shlex.split(shlex.split(e[1][-1])[-1])[-1]) for e in w.effects if e[0] == "run" and e[1][0] == "ssh"]
        self.assertEqual([a[3:] for a in asked if "--route" in a],
                         [["WK_ZED_PUBKEY=ssh-ed25519 AAAAzed wk zed key", "/home/u/wk/tools/wk", "zed", "demo", "--route"]])


